import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import config  # noqa: E402

OFFICER_PATTERNS = ("POLICE/PEACE", "PUBLIC SERVICE", "TRAFFIC AGENT", "PEACE OFFICER")
RETAIL_PD_PATTERNS = ("SHOPLIFTING", "CHAIN STORE", "COMMERCIAL", "BANK", "DEPARTMENT STORE", "DELIVERY", "LICENSED MEDALLION", "GAS STATION", "LIQUOR STORE", "CHECK CASHING", "PHARMACY", "SUPERMARKET", "RESTAURANT", "BODEGA", "CLOTHING")
RETAIL_PREMISES = ("CHAIN STORE", "DEPARTMENT STORE", "CLOTHING/BOUTIQUE", "DRUG STORE", "VARIETY STORE", "SMALL MERCHANT", "FOOD SUPERMARKET", "GROCERY/BODEGA", "JEWELRY", "LIQUOR STORE", "TELECOMM. STORE", "SHOE", "BEAUTY & NAIL SALON", "CANDY STORE", "STORE UNCLASSIFIED", "BANK", "CHECK CASHING BUSINESS", "FAST FOOD", "RESTAURANT/DINER")


def class_from_strings(ky_cd: str, pd_desc: str, prem: str) -> str:
    d = (pd_desc or "").upper()
    p = (prem or "").upper()
    if ky_cd == "101":
        return "homicide"
    if ky_cd == "106":
        return "officer_assault" if any(s in d for s in OFFICER_PATTERNS) else "other_assault"
    if ky_cd == "105":
        if any(s in d for s in RETAIL_PD_PATTERNS) or any(s in p for s in RETAIL_PREMISES):
            return "retail_robbery"
        return "street_robbery"
    return "not_violent"


def load_pd_crosswalk() -> pd.DataFrame | None:
    p = config.CROSSWALKS / "pd_code_classes.csv"
    if not p.exists():
        return None
    x = pd.read_csv(p, dtype=str)
    return x


def classify_frame(df: pd.DataFrame) -> pd.Series:
    """Vectorized class assignment: the pd crosswalk decides for ky 101/106 and for 105 codes marked
    retail by code; premise-based retail robbery is decided row by row (premise is not in the crosswalk)."""
    ky = df["ky_cd"].astype(str)
    pdd = df["pd_desc"].fillna("").str.upper()
    prem = df["prem_typ_desc"].fillna("").str.upper()
    out = pd.Series("not_violent", index=df.index, dtype=object)
    out[ky == "101"] = "homicide"
    is106 = ky == "106"
    officer = pdd.str.contains("|".join(OFFICER_PATTERNS), regex=True)
    out[is106 & officer] = "officer_assault"
    out[is106 & ~officer] = "other_assault"
    is105 = ky == "105"
    retail_pd = pdd.str.contains("|".join(RETAIL_PD_PATTERNS), regex=True)
    retail_prem = prem.isin([s.upper() for s in RETAIL_PREMISES])
    out[is105 & (retail_pd | retail_prem)] = "retail_robbery"
    out[is105 & ~(retail_pd | retail_prem)] = "street_robbery"
    return out


def is_transit(df: pd.DataFrame) -> pd.Series:
    j = df["juris_desc"].fillna("").str.upper().str.contains("TRANSIT")
    p = df["prem_typ_desc"].fillna("").str.upper().str.contains("TRANSIT")
    return j | p


def zone_frame(df: pd.DataFrame, at_courthouse: pd.Series) -> pd.Series:
    out = pd.Series("street_stores", index=df.index, dtype=object)
    out[is_transit(df)] = "transit"
    out[at_courthouse] = "courthouse"
    return out


def premise_group(prem: pd.Series) -> pd.Series:
    p = prem.fillna("(null)").str.upper()
    rules = [
        ("(null)", "unrecorded"), ("STREET", "street"), ("TRANSIT", "transit"), ("RESIDENCE - APT", "apartment house"),
        ("RESIDENCE-HOUSE", "house"), ("RESIDENCE - PUBLIC", "public housing"), ("DEPARTMENT STORE", "department store"),
        ("CHAIN STORE", "chain store"), ("CLOTHING", "clothing store"), ("DRUG STORE", "drug store"), ("VARIETY", "variety store"),
        ("GROCERY", "bodega"), ("FOOD SUPERMARKET", "supermarket"), ("FAST FOOD", "fast food"), ("RESTAURANT", "restaurant"),
        ("BAR/NIGHT", "bar"), ("HOTEL", "hotel"), ("HOMELESS SHELTER", "shelter"), ("PUBLIC BUILDING", "public building"),
        ("COMMERCIAL", "commercial building"), ("BANK", "bank"), ("PARK", "park"), ("SCHOOL", "school"), ("HOSPITAL", "hospital"),
        ("PARKING", "parking"), ("OTHER", "other"),
    ]
    out = pd.Series("other", index=prem.index, dtype=object)
    done = pd.Series(False, index=prem.index)
    for pat, name in rules:
        m = p.str.contains(pat, regex=False) & ~done
        out[m] = name
        done |= m
    return out


def hour_from_tm(tm: pd.Series) -> pd.Series:
    return pd.to_numeric(tm.str.slice(0, 2), errors="coerce")


def flags(df: pd.DataFrame) -> pd.DataFrame:
    """Time, lag and span flags shared by every stage."""
    fr = pd.to_datetime(df["cmplnt_fr_dt"].str.slice(0, 10), errors="coerce")
    to = pd.to_datetime(df["cmplnt_to_dt"].str.slice(0, 10), errors="coerce")
    rpt = pd.to_datetime(df["rpt_dt"].str.slice(0, 10), errors="coerce")
    fr_tm = pd.to_timedelta(df["cmplnt_fr_tm"], errors="coerce")
    to_tm = pd.to_timedelta(df["cmplnt_to_tm"], errors="coerce")
    span_h = ((to + to_tm) - (fr + fr_tm)).dt.total_seconds() / 3600
    out = pd.DataFrame(index=df.index)
    out["date"] = fr
    out["year"] = fr.dt.year
    out["month"] = fr.dt.month
    out["doy"] = fr.dt.dayofyear
    out["dow"] = fr.dt.dayofweek  # Mon=0
    out["hour"] = hour_from_tm(df["cmplnt_fr_tm"].fillna(""))
    out["default_time"] = df["cmplnt_fr_tm"].isin(config.DEFAULT_TIMES)
    out["on_the_hour"] = df["cmplnt_fr_tm"].fillna("").str.slice(3, 8) == "00:00"
    out["lag_days"] = (rpt - fr).dt.days
    out["span_hours"] = span_h
    out["rpt_date"] = rpt
    out["night"] = out["hour"].isin(config.NIGHT_HOURS)
    return out
