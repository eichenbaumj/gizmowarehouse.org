"""Class, zone and flag rules. Table-driven where a table exists (crosswalks/pd_code_classes.csv,
generated by 01b_make_crosswalks.py from the citywide coding aggregate and then hand-reviewed);
the string rules below are the generator and the fallback for an unseen pd code."""
from __future__ import annotations

import sys
