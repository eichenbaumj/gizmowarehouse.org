def _def(text: str, name: str, path: str) -> str:
    lines = text.split("\n")
    starts = [i for i, ln in enumerate(lines) if re.match(rf"def {re.escape(name)}\(", ln)]
    if len(starts) != 1:
        raise ValueError(f"{path}: expected one top-level 'def {name}(', found {len(starts)}")
    i = starts[0]
    j = i + 1
    while j < len(lines) and (lines[j] == "" or lines[j][0] in " \t)" ):
        j += 1
    body = lines[i:j]
    while body and body[-1].strip() == "":
        body.pop()
    return "\n".join(body)


def _class(text: str, name: str, path: str) -> str:
    """A top-level class, with the decorator lines directly above it, to its last line (as _def)."""
    lines = text.split("\n")
    starts = [i for i, ln in enumerate(lines) if re.match(rf"class {re.escape(name)}\b", ln)]
    if len(starts) != 1:
        raise ValueError(f"{path}: expected one top-level 'class {name}', found {len(starts)}")
    i = starts[0]
    while i > 0 and lines[i - 1].startswith("@"):
        i -= 1
    j = starts[0] + 1
    while j < len(lines) and (lines[j] == "" or lines[j][0] in " \t)"):
        j += 1
    body = lines[i:j]
    while body and body[-1].strip() == "":
        body.pop()
    return "\n".join(body)


def _line(text: str, locator: str, path: str) -> str:
    hits = [ln for ln in text.split("\n") if ln.lstrip().startswith(locator)]
    if len(hits) != 1:
        raise ValueError(f"{path}: expected one line starting {locator!r}, found {len(hits)}")
    return hits[0]


def extract(path: str, kind: str, locator) -> str:
    text = (ROOT / path).read_text()
    if kind == "file":
        return text.rstrip("\n")
    if kind == "def":
        return _def(text, locator, path)
    if kind == "class":
        return _class(text, locator, path)
    if kind == "line":
        return _line(text, locator, path)
    if kind == "lines":
        return "\n".join(_line(text, loc, path) for loc in locator)
    raise ValueError(kind)


def transcribe() -> str:
    """The transcription as markdown: each source's text inside a fence, unchanged."""
    out = []
    for heading, path, kind, locator in SOURCES:
        body = extract(path, kind, locator)
        fence = "````"
        where = path if kind == "file" else f"{path}, {'`' + locator + '`' if kind in ('def', 'class') else 'as it stands'}"
        out.append(f"**{heading}** ({where})\n\n{fence}text\n{body}\n{fence}")
    return "\n\n".join(out)


def in_ledger() -> str:
    text = LEDGER.read_text()
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        raise ValueError(f"{LEDGER}: the transcription's markers are missing or repeated")
    return text.split(BEGIN)[1].split(END)[0].strip("\n")


def main() -> int:
    if "--check" in sys.argv[1:]:
        same = in_ledger() == transcribe()
        print("the ledger's transcription matches the sources" if same else
              "THE SOURCES HAVE MOVED: the ledger's transcription no longer matches the plan or the code. A change to a pool "
              "restriction is a research decision (D-56): log it, then transcribe again with a dated note.")
        return 0 if same else 1
    print(transcribe())
    return 0


if __name__ == "__main__":
    sys.exit(main())
